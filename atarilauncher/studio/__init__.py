"""Hoodlum Asylum Studio - a small, beginner-friendly beat maker, voice recorder and mixer inside Code.

Everything is made from scratch: the sounds are synthesised with numpy (no samples, nothing from anyone else) and the beat
patterns are generated by an algorithm that lives behind a small interface (beatgen.BeatGenerator), so a real AI music model
(local or online) can be plugged in later without touching the screens.

numpy is the only extra library; without it the Studio screen explains how to add it and the rest of Code is unaffected.
"""


def numpy_available() -> bool:
    try:
        import numpy  # noqa: F401
        return True
    except ImportError:
        return False
